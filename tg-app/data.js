// Форматирует дату для отображения: "25 июня, четверг"
function formatDateLong(dateStr) {
  const d = new Date(dateStr);
  const weekdaysFull = ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'];
  return `${d.getDate()} ${RU.monthsGen[d.getMonth()]}, ${weekdaysFull[d.getDay()]}`;
}

// Форматирует цену: 2500 → "2 500 ₽"
function formatPrice(price) {
  return price.toLocaleString('ru-RU') + ' ₽';
}
