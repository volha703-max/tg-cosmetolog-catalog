// Определяет занят ли слот (псевдослучайно для демо)
// В реальном приложении — запрос к бэкенду
function isSlotTaken(dateStr, time) {
  const seed = dateStr.replace(/-/g, '') + time.replace(':', '');
  const hash = seed.split('').reduce((acc, ch) => acc * 31 + ch.charCodeAt(0), 7);
  return Math.abs(hash) % 3 === 0; // примерно треть слотов занята
}

